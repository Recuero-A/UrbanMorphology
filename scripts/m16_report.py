"""Milestone 16 confirmatory report (docs/M16_PROTOCOL.md §5-6): outputs/m16/REPORT.md and report.json.

Reads only stored runs of configs/m16_plans/{confirm,named,sweeps}.json; nothing is regenerated. Recognisability uses
the nearest-centroid classifier fitted on the `calib` real references (metrics/recognise.py). CIs: two-level
bootstrap over sites, then seeds within site (5000 resamples); paired contrasts use the same (site, seed).

    python scripts/m16_report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import numpy as np
import pandas as pd

from m16_plans import CONF_SEEDS, SAMPLERS, STYLES, proposals
from urbanmorph.experiments.jsonio import atomic_json
from urbanmorph.experiments.runner import load_run
from urbanmorph.metrics.recognise import FEATURES, fit, loo_accuracy

RUNS = ROOT / "outputs" / "m16" / "runs"
OUT = ROOT / "outputs" / "m16"
B = 5000
FZ = json.loads((ROOT / "configs" / "m16_frozen.json").read_text())["alpha"]
PRIMARY = {"grid": [("block_rect_share", +1), ("stroke_xjunc_lw", +1), ("share_4way", +1), ("circuity_200_350", -1)],
           "organic": [("block_logA_sd", +1), ("jangle_right_share", -1), ("share_3way", +1), ("block_phi_med", -1)],
           "radial": [("spokes_long", +1), ("ring_cover_max", +1), ("sector_circ", -1)],
           "culdesac": [("tree_len_share", +1), ("term_attached_share", +1), ("od_unreach_land", -1)]}
TERRAIN = ["share_gt15", "share_gt10", "grade_p90_m13", "contour_align", "street_km", "coverage_60", "empty", "bridges"]
SLOPED = ("incline8", "incline15", "ridge", "valley", "water")


def base(m, sites="syn_conf", backbone="TN_s0"):
    return {"sites": sites, "backbone": backbone, "method": m, "start": "centre", "seeds": CONF_SEEDS}


def mode_spec(m, st, mode, backbone="TN_s0", **extra):
    b = base(m, backbone=backbone)
    if mode == "off":
        return {**b, "style": "off"}
    if mode == "rerank":
        return {**b, "style": st}
    ref = m if m in SAMPLERS else {"M13-SMC": "M*", "NA-SMC": "NA-fixed"}[m]
    p = proposals(mode, FZ[ref][st][mode]["prop_alpha"])
    p.update(extra)
    return {**b, "style": st, "proposals": p}


def rows(spec) -> dict:
    r = load_run(spec, RUNS)
    return {} if r is None else {(x["site"], int(sd)): x for sd, v in r["seeds"].items() for x in v["rows"]}


def val(x, k):
    v = x.get(k) if x else None
    return float(v) if v is not None and np.isfinite(v) else np.nan


def cond(site):
    return site.split("_", 1)[1]


def boot(d: dict, rng):
    """d: site -> list of values. Mean of site means and a two-level percentile CI."""
    d = {s: [x for x in v if np.isfinite(x)] for s, v in d.items()}
    d = {s: v for s, v in d.items() if v}
    if not d:
        return np.nan, np.nan, np.nan
    sites = list(d)
    est = float(np.mean([np.mean(d[s]) for s in sites]))
    bs = [np.mean([np.mean(rng.choice(d[s], len(d[s]))) for s in rng.choice(sites, len(sites))]) for _ in range(B)]
    return est, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def per_site(R: dict, f, keep=None) -> dict:
    out = {}
    for (s, sd), x in R.items():
        if keep is None or keep(s):
            out.setdefault(s, []).append(f(x))
    return out


def paired_site(A: dict, Bd: dict, f, keep=None) -> dict:
    out = {}
    for key in A:
        if key in Bd and (keep is None or keep(key[0])):
            out.setdefault(key[0], []).append(f(Bd[key]) - f(A[key]))
    return out


def fmt(x, n=3):
    return "–" if x is None or not np.isfinite(x) else f"{x:.{n}f}"


def ci(t, n=3):
    return f"{fmt(t[0], n)} [{fmt(t[1], n)}, {fmt(t[2], n)}]"


def main():
    rng = np.random.default_rng(16)
    refs = pd.read_csv(ROOT / "configs" / "m16_style_refs" / "metrics.csv")
    cal = refs[refs.subset == "calib"]
    clf = fit(cal.to_dict("records"), cal["style"].tolist())
    loo = loo_accuracy(cal.to_dict("records"), cal["style"].tolist())
    srt = refs[refs.subset == "sort"]
    sort_acc = float(np.mean(np.array(clf.predict(srt.to_dict("records"))) == srt["style"].values))
    J = {"classifier": {"loo_calib": loo, "sort_accuracy": sort_acc, "features": FEATURES}}
    L = ["# Milestone 16 report: style-aware proposals, recognisability and terrain (CONFIRMATORY, synthetic)", "",
         "Generated by `scripts/m16_report.py` from stored runs. Sites `syn_conf` (fresh; declared before any M16 run), "
         f"seeds 301–320, fixed start, temperature 0.5, backbone TN_s0 unless noted. Frozen settings: `configs/m16_frozen.json`. "
         "CIs: two-level bootstrap (sites, then seeds). Six synthetic sites: between-site uncertainty is coarse.", "",
         "## 0. Recognisability classifier (fitted on real `calib` references only)", "",
         f"Leave-one-out accuracy on the 20 calib windows: **{loo:.2f}**; accuracy on the 16 separate `sort` windows: "
         f"**{sort_acc:.2f}** (chance 0.25; protocol sanity threshold 0.6 → {'passed' if loo >= 0.6 else 'FAILED: inconclusive'}).", ""]
    off = {m: rows(mode_spec(m, None, "off")) for m in SAMPLERS}
    # 1. recognition and coverage
    L += ["## 1. Recognition rate and coverage (primary)", "",
          "Recognised = the classifier returns the requested style. Verdict: rate ≥ 0.5 AND (proposals rate − rerank rate) "
          "lower bound > 0, at useful coverage (coverage_60 ≥ 0.8 × off and empty ≤ off + 0.05).", "",
          "| Sampler | Style | Mode | recognition [95% CI] | − rerank [95% CI] | coverage / off | empty | street km | verdict |",
          "|---|---|---|---|---|---|---|---|---|"]
    rec, J["recognition"] = {}, {}
    for m in SAMPLERS:
        cov_off = np.nanmean([val(x, "coverage_60") for x in off[m].values()])
        emp_off = np.nanmean([val(x, "empty") for x in off[m].values()])
        for st in STYLES:
            for mode in ("off", "rerank", "style", "style_topo"):
                R = off[m] if mode == "off" else rows(mode_spec(m, st, mode))
                if not R:
                    continue
                keys = list(R)
                pred = clf.predict([R[k] for k in keys])
                hit = {k: float(p == st) for k, p in zip(keys, pred)}
                rec[(m, st, mode)] = hit
                r = boot(per_site({k: hit[k] for k in keys}, lambda x: x), rng) if False else \
                    boot({s: [hit[k] for k in keys if k[0] == s] for s in {k[0] for k in keys}}, rng)
                d = (np.nan,) * 3
                if mode in ("style", "style_topo") and (m, st, "rerank") in rec:
                    rr = rec[(m, st, "rerank")]
                    d = boot({s: [hit[k] - rr[k] for k in keys if k[0] == s and k in rr] for s in {k[0] for k in keys}}, rng)
                cov = np.nanmean([val(x, "coverage_60") for x in R.values()]) / cov_off
                emp = np.nanmean([val(x, "empty") for x in R.values()])
                km = np.nanmean([val(x, "street_km") for x in R.values()])
                useful = cov >= 0.8 and emp <= emp_off + 0.05
                verdict = ""
                if mode in ("style", "style_topo"):
                    verdict = "recognisable" if (r[0] >= 0.5 and d[1] > 0 and useful) else (
                        "not met" + ("" if useful else " (coverage)"))
                L.append(f"| {m} | {st} | {mode} | {ci(r, 2)} | {ci(d, 2) if mode in ('style', 'style_topo') else ''} | "
                         f"{cov:.2f} | {emp:.2f} | {km:.2f} | {verdict} |")
                J["recognition"][f"{m}|{st}|{mode}"] = {"rate": r, "minus_rerank": d, "coverage_ratio": cov, "empty": emp,
                                                        "street_km": km, "verdict": verdict}
    # per-site recognition
    L += ["", "Recognition per condition (proposals + topology):", "",
          "| Sampler | Style | " + " | ".join(("flat", "incline8", "incline15", "ridge", "valley", "water")) + " |",
          "|---|---|" + "---|" * 6]
    for m in SAMPLERS:
        for st in STYLES:
            h = rec.get((m, st, "style_topo"), {})
            L.append(f"| {m} | {st} | " + " | ".join(fmt(np.mean([v for k, v in h.items() if cond(k[0]) == c]) if h else np.nan, 2)
                                                     for c in ("flat", "incline8", "incline15", "ridge", "valley", "water")) + " |")
    # confusion
    L += ["", "What the classifier returns (all sites and seeds, proposals + topology):", "",
          "| Sampler | requested | grid | organic | radial | culdesac |", "|---|---|---|---|---|---|"]
    for m in SAMPLERS:
        for st in STYLES:
            R = rows(mode_spec(m, st, "style_topo"))
            if R:
                p = pd.Series(clf.predict(list(R.values()))).value_counts(normalize=True)
                L.append(f"| {m} | {st} | " + " | ".join(f"{p.get(s, 0):.2f}" for s in STYLES) + " |")
    # 2. primary outcomes
    L += ["", "## 2. Primary outcomes (not optimised by any rule), paired against rerank and against off", "",
          "| Sampler | Style | Outcome (expected) | real calib mean | off | rerank | proposals | prop.+topology | prop.+topo − rerank [95% CI] |",
          "|---|---|---|---|---|---|---|---|---|"]
    J["primary"] = {}
    for m in SAMPLERS:
        for st in STYLES:
            Rr, Rs, Rt = (rows(mode_spec(m, st, x)) for x in ("rerank", "style", "style_topo"))
            for k, sgn in PRIMARY[st]:
                mean = lambda R: np.nanmean([val(x, k) for x in R.values()]) if R else np.nan
                d = boot(paired_site(Rr, Rt, lambda x: val(x, k)), rng) if Rt else (np.nan,) * 3
                realm = float(np.nanmean(cal[cal["style"] == st][k])) if k in cal else np.nan
                L.append(f"| {m} | {st} | {k} ({'↑' if sgn > 0 else '↓'}) | {fmt(realm)} | {fmt(mean(off[m]))} | {fmt(mean(Rr))} | "
                         f"{fmt(mean(Rs))} | {fmt(mean(Rt))} | {ci(d)} |")
                J["primary"][f"{m}|{st}|{k}"] = {"off": mean(off[m]), "rerank": mean(Rr), "style": mean(Rs),
                                                 "style_topo": mean(Rt), "topo_minus_rerank": d, "real": realm}
    # 3. hypothesis H
    L += ["", "## 3. Hypothesis H: do targeted proposals recover viable continuations?", "",
          "Per decision (proposals + topology runs): share of decisions with no feasible learned candidate within 15° of a "
          "pattern direction, share of those rescued by a feasible style candidate, accepted moves from style candidates, "
          "evaluations per seed. Test: recognition, proposals + topology − matched-compute unguided pool (K = 8 + mean "
          "style candidates per decision; rerank), paired.", "",
          "| Sampler | Style | no aligned learned | rescued | accepted from style | evaluations / seed (topo / pool) | coverage topo / pool | recognition topo − pool [95% CI] |",
          "|---|---|---|---|---|---|---|---|"]
    J["H"] = {}
    for m in SAMPLERS:
        for st in STYLES:
            Rt = rows(mode_spec(m, st, "style_topo"))
            pool_spec = [s for s in json.loads((ROOT / "configs" / "m16_plans" / "confirm.json").read_text())["runs"]
                         if s.get("control") == "matched_pool" and s["method"] == m and s["style"] == st]
            Rp = rows(pool_spec[0]) if pool_spec else {}
            if not Rt:
                continue
            lg = lambda R, k: sum(x["log"].get(k, 0) for x in R.values())
            na = lg(Rt, "no_aligned_model") / max(lg(Rt, "prop_decisions"), 1)
            rs = lg(Rt, "rescued_aligned") / max(lg(Rt, "no_aligned_model"), 1)
            ch = lg(Rt, "chosen_style") / max(lg(Rt, "committed"), 1)
            ev = lambda R: (lg(R, "cand_evals") + lg(R, "cand_style")) / max(len({k[1] for k in R}), 1)
            cv = lambda R: np.nanmean([val(x, "coverage_60") for x in R.values()])
            d = (np.nan,) * 3
            if Rp:
                hp = dict(zip(Rp, [float(p == st) for p in clf.predict(list(Rp.values()))]))
                ht = rec[(m, st, "style_topo")]
                d = boot({s: [ht[k] - hp[k] for k in ht if k[0] == s and k in hp] for s in {k[0] for k in ht}}, rng)
            L.append(f"| {m} | {st} | {na:.2f} | {rs:.2f} | {ch:.2f} | {ev(Rt):.0f} / {ev(Rp) if Rp else float('nan'):.0f} | "
                     f"{cv(Rt):.3f} / {cv(Rp) if Rp else float('nan'):.3f} | {ci(d, 2)} |")
            J["H"][f"{m}|{st}"] = {"no_aligned": na, "rescued": rs, "accepted_style": ch, "minus_pool": d}
    # 4. ablations and controls
    L += ["", "## 4. Ablations and controls (recognition rate; street km; OD unreachable)", "",
          "| Sampler | Style | Variant | recognition [95% CI] | street km | coverage | OD unreachable |", "|---|---|---|---|---|---|---|"]
    J["controls"] = {}
    plan = json.loads((ROOT / "configs" / "m16_plans" / "confirm.json").read_text())["runs"]
    for m in list(SAMPLERS) + ["M13-SMC", "NA-SMC"]:
        for st in STYLES:
            variants = []
            if m in SAMPLERS:
                variants += [("prop.+topology (frozen)", mode_spec(m, st, "style_topo")),
                             ("rule-only (no learned candidates)", mode_spec(m, st, "style_topo", prop_rule_only=True)),
                             ("importance-weighted (target unchanged)", mode_spec(m, st, "style_topo", prop_weight="is")),
                             ("TNse backbone (amendment 1)", mode_spec(m, st, "style_topo", backbone="TNse_s0"))]
                if m == "M*":
                    trig = [s for s in plan if s["method"] == m and s["style"] == st and s.get("proposals", {}).get("prop_trigger", "always") != "always"]
                    variants += [(f"trigger {s['proposals']['prop_trigger']}", s) for s in trig]
                if m == "NA-fixed" and st == "culdesac":
                    variants.append(("dead-end penalty waived for rooted branches", mode_spec(m, st, "style_topo", dead_exempt_local=True)))
            else:
                variants += [("prop.+topology", mode_spec(m, st, "style_topo"))]
            for lab, spec in variants:
                R = rows(spec)
                if not R:
                    L.append(f"| {m} | {st} | {lab} | missing | | | |")
                    continue
                hit = dict(zip(R, [float(p == st) for p in clf.predict(list(R.values()))]))
                r = boot({s: [hit[k] for k in hit if k[0] == s] for s in {k[0] for k in hit}}, rng)
                mm = lambda k: np.nanmean([val(x, k) for x in R.values()])
                L.append(f"| {m} | {st} | {lab} | {ci(r, 2)} | {mm('street_km'):.2f} | {mm('coverage_60'):.3f} | {mm('od_unreach_land'):.3f} |")
                J["controls"][f"{m}|{st}|{lab}"] = {"rate": r, "km": mm("street_km"), "od": mm("od_unreach_land")}
    # 5. terrain
    L += ["", "## 5. Terrain: true vs flattened vs mismatched input (sloped and river conditions; scored on the true terrain)", "",
          "| Sampler | Style / mode | input | > 15 % | > 10 % | grade p90 (30 m) | gradient align. | street km | coverage | empty | bridges |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    J["terrain"] = {}
    keep = lambda s: cond(s) in SLOPED
    for m in SAMPLERS:
        for st in ["off"] + list(STYLES):
            sp = mode_spec(m, st, "off" if st == "off" else "style_topo")
            Rt = rows(sp)
            Rf = rows({**sp, "shown": "flatten"})
            Rm = rows({**sp, "sites": "syn_conf_nonflat", "shown": "syn_conf_mismatch"})
            for lab, R in (("true", Rt), ("flattened", Rf), ("mismatched", Rm)):
                if not R:
                    continue
                mm = [np.nanmean([val(x, k) for (s, _), x in R.items() if keep(s)]) for k in TERRAIN]
                L.append(f"| {m} | {st if st == 'off' else st + ' prop.+topo'} | {lab} | " + " | ".join(fmt(v) for v in mm) + " |")
            for lab, R in (("flattened", Rf), ("mismatched", Rm)):
                if Rt and R:
                    d = boot(paired_site(R, Rt, lambda x: val(x, "share_gt15"), keep), rng)
                    # density-matched: residual of share_gt15 after regressing on log street km (pooled true + other)
                    ks = [k for k in Rt if k in R and keep(k[0])]
                    y = np.array([val(Rt[k], "share_gt15") for k in ks] + [val(R[k], "share_gt15") for k in ks])
                    x = np.array([np.log(max(val(Rt[k], "street_km"), 0.05)) for k in ks] + [np.log(max(val(R[k], "street_km"), 0.05)) for k in ks])
                    g = np.r_[np.ones(len(ks)), np.zeros(len(ks))]
                    ok = np.isfinite(y) & np.isfinite(x)
                    coef = np.linalg.lstsq(np.c_[np.ones(ok.sum()), x[ok], g[ok]], y[ok], rcond=None)[0] if ok.sum() > 3 else [np.nan] * 3
                    L.append(f"| {m} | {st if st == 'off' else st + ' prop.+topo'} | true − {lab}: > 15 % {ci(d)}; adjusted for log km {fmt(coef[2])} | | | | | | | | |")
                    J["terrain"][f"{m}|{st}|true-{lab}"] = {"diff": d, "adjusted": float(coef[2])}
    # 6. connectivity and diversity
    L += ["", "## 6. Connectivity and diversity", "",
          "| Sampler | Style | Mode | OD unreachable (land) | circuity 200–350 m | Jaccard diversity |", "|---|---|---|---|---|---|"]
    for m in SAMPLERS:
        for st in STYLES:
            for mode in ("off", "rerank", "style_topo"):
                if mode == "off" and st != STYLES[0]:
                    continue
                spec = mode_spec(m, st, mode)
                r = load_run(spec, RUNS)
                if r is None:
                    continue
                R = rows(spec)
                div = np.nanmean([d.get("jaccard_distance", np.nan) for d in r.get("diversity", [])]) if r.get("diversity") else np.nan
                L.append(f"| {m} | {st if mode != 'off' else '–'} | {mode} | {fmt(np.nanmean([val(x, 'od_unreach_land') for x in R.values()]))} | "
                         f"{fmt(np.nanmean([val(x, 'circuity_200_350') for x in R.values()]))} | {fmt(div)} |")
    # 7. named real sites
    L += ["", "## 7. Named real sites (RECURRING COMPARISON, not confirmatory; seeds 1–5)", "",
          "| Source | Sampler | Mode | site | street km | > 15 % | OD unreachable | recognised as requested |", "|---|---|---|---|---|---|---|---|"]
    named = json.loads((ROOT / "configs" / "m16_plans" / "named.json").read_text())["runs"]
    for spec in named:
        R = rows(spec)
        if not R:
            continue
        mode = "prop.+topo" if spec.get("proposals") else ("rerank" if spec["style"] != "off" else f"off ({spec['backbone']})")
        for site in sorted({s for s, _ in R}):
            xs = [x for (s, _), x in R.items() if s == site]
            rr = np.mean([p == spec["style"] for p in clf.predict(xs)]) if spec["style"] != "off" else np.nan
            L.append(f"| {spec['sites'][6:]} | {spec['method']} | {spec['style']} {mode} | {site[6:]} | "
                     f"{np.nanmean([val(x, 'street_km') for x in xs]):.2f} | {fmt(np.nanmean([val(x, 'share_gt15') for x in xs]))} | "
                     f"{fmt(np.nanmean([val(x, 'od_unreach_land') for x in xs]))} | {fmt(rr, 2)} |")
    # 8. sweeps
    sw = ROOT / "configs" / "m16_plans" / "sweeps.json"
    if sw.exists():
        L += ["", "## 8. Separate sweeps (secondary): displacement temperature and stop bias, M* proposals + topology", "",
              "| Style | Setting | recognition | street km | coverage | > 15 % (sloped) |", "|---|---|---|---|---|---|"]
        for spec in json.loads(sw.read_text())["runs"]:
            R = rows(spec)
            if not R:
                continue
            st = spec["style"]
            hit = np.mean([p == st for p in clf.predict(list(R.values()))])
            lab = f"T = {spec['temperature']}" if "temperature" in spec else f"stop bias {spec['overrides']['stop_bias']:+.2f}"
            L.append(f"| {st} | {lab} | {hit:.2f} | {np.nanmean([val(x, 'street_km') for x in R.values()]):.2f} | "
                     f"{np.nanmean([val(x, 'coverage_60') for x in R.values()]):.3f} | "
                     f"{fmt(np.nanmean([val(x, 'share_gt15') for (s, _), x in R.items() if keep(s)]))} |")
    (OUT / "REPORT.md").write_text("\n".join(L) + "\n")
    atomic_json(OUT / "report.json", J)
    print("\n".join(L))


if __name__ == "__main__":
    main()
