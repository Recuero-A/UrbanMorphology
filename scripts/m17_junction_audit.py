"""Milestone 17, step 1: reproduce the close-junction table with the formal metrics (graphs/junctions.py).

Sets (every source traced in the output):
* TRAINING: the 685 training tiles of data/processed/m12/graphs3d.pkl (OSM -> build_graph, 8 m greedy snap);
* real M15 pilot: data/processed/m15/real/graphs.pkl (120 windows, same build);
* real style references: data/processed/m16/style_refs/graphs.pkl (36 windows, same build), per style;
* real KAIST: the 9 campus windows of the terrain pack, vehicular roads (+ service), same build;
* generated KAIST (outputs/m16/kaist/all_cache/<method>_s<seed>.pkl, seeds 1-3) in two representations:
  RAW = the generated graph itself, focal junctions inside each 512 m window, neighbours from the whole 1536 m
  domain (buffered); REBUILT = each window's lines clipped and passed through the same build_graph as the real data
  (scripts/m16_kaist_styles.windows_of; 8 m greedy snap, 30 m resampling).
Statistics: pooled over focal junctions and averaged over windows (both labelled), denominators, a threshold sweep,
and topology-aware consolidation at 10 m (pairwise; path <= 15 m).

    python scripts/m17_junction_audit.py   ->  outputs/m17/junction_audit.{md,json}
"""
from __future__ import annotations

import json
import pickle
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import numpy as np

from urbanmorph.experiments.jsonio import atomic_json
from urbanmorph.graphs.junctions import SWEEP_M, junction_row, summarise

OUT = ROOT / "outputs" / "m17"


def sets():
    from m16_kaist_all import CACHE, ORDER, key_of
    from m16_kaist_styles import windows_of
    from m16_kaist_campus import PACK, W
    d = pickle.loads((ROOT / "data" / "processed" / "m12" / "graphs3d.pkl").read_bytes())
    yield "TRAINING (685 tiles, 9 cities)", "data/processed/m12/graphs3d.pkl[train]", [junction_row(g) for _, _, g in d["train"]]
    yield ("real M15 pilot (120)", "data/processed/m15/real/graphs.pkl",
           [junction_row(g) for _, _, g, _ in pickle.loads((ROOT / "data" / "processed" / "m15" / "real" / "graphs.pkl").read_bytes())])
    refs = pickle.loads((ROOT / "data" / "processed" / "m16" / "style_refs" / "graphs.pkl").read_bytes())
    for st in ("grid", "organic", "radial", "culdesac"):
        yield f"real refs {st}", "data/processed/m16/style_refs/graphs.pkl", [junction_row(g) for _, s, _, g in refs if s == st]
    yield ("real KAIST (vehicular)", "data/processed/m16/pack/streets/KAIST_CAMPUS_r*c*__vehicular.pkl",
           [junction_row(pickle.loads(f.read_bytes())) for f in sorted((PACK / "streets").glob("KAIST_CAMPUS_r?c?__vehicular.pkl"))])
    for lab in ORDER:
        raw, reb, ids = [], [], []
        for seed in (1, 2, 3):
            f = CACHE / f"{key_of(lab)}_s{seed}.pkl"
            g = pickle.loads(f.read_bytes())["graph"]
            ids.append(str(f.relative_to(ROOT)))
            for r in range(3):
                for c in range(3):
                    raw.append(junction_row(g, window=(c * W, r * W, c * W + W, r * W + W)))
            reb += [junction_row(wg) if wg is not None else None for _, wg in windows_of(g)]
        yield f"{lab} [raw]", "; ".join(ids), raw
        yield f"{lab} [rebuilt]", "; ".join(ids), reb


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    res = []
    for name, src, rows in sets():
        s = summarise(rows)
        res.append({"set": name, "source": src, **s})
        print(name, {k: round(v, 3) if isinstance(v, float) else v for k, v in s.items() if k in
                     ("windows", "windows_lt2_focal", "focal_junctions", "window_close15", "pooled_close15",
                      "pooled_nn_p10", "window_consol10")}, flush=True)
    L = ["# M17 step 1: close-junction audit (reproduction with the formal metrics)", "",
         "Generated by `scripts/m17_junction_audit.py`; definitions in `graphs/junctions.py` / `docs/M17_METRICS.md`. "
         "Focal junctions: >= 40 m inside the window. close15 = share of focal junctions whose nearest other junction is "
         "< 15 m (pairwise). Window = mean over windows with >= 2 focal junctions; pooled = all focal junctions together. "
         "consol10 = focal junctions / topology-aware clusters (pairwise <= 10 m and an at-grade path <= 15 m). "
         "Generated KAIST: RAW (as generated, buffered neighbours) and REBUILT (same build_graph as the real data).", "",
         "| Set | windows | < 2 focal | focal junctions | focal / km2 | close15 (window) | close15 (pooled) | nn p10 (window) | nn p10 (pooled) | consol10 (window) |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    f = lambda x, n=3: "–" if x is None or not np.isfinite(x) else f"{x:.{n}f}"
    for r in res:
        L.append(f"| {r['set']} | {r['windows']} | {r['windows_lt2_focal']} | {r['focal_junctions']} | {f(r['focal_density_km2'], 0)} | "
                 f"{f(r['window_close15'])} | {f(r['pooled_close15'])} | {f(r['window_nn_p10'], 1)} | {f(r['pooled_nn_p10'], 1)} | {f(r['window_consol10'])} |")
    L += ["", "Threshold sweep (pooled share of focal junctions with a neighbour closer than tau):", "",
          "| Set | " + " | ".join(f"{t:g} m" for t in SWEEP_M) + " |", "|---|" + "---|" * len(SWEEP_M)]
    for r in res:
        L.append(f"| {r['set']} | " + " | ".join(f(r[f'pooled_close_{t:g}']) for t in SWEEP_M) + " |")
    (OUT / "junction_audit.md").write_text("\n".join(L) + "\n")
    atomic_json(OUT / "junction_audit.json", res)
    return 0


if __name__ == "__main__":
    sys.exit(main())
