"""Milestone 16, part 1: report of the milestone replays and the terrain-regression diagnosis (docs/M16_PROTOCOL.md §7).

Reads the stored runs of configs/m16_plans/replay.json (outputs/m16/runs) and writes outputs/m16/replay_report.{md,json}.
Paired differences use the same (site, seed); CIs: two-level bootstrap (sites, then seeds within site), 5000 resamples.

    python scripts/m16_replay_report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np

from urbanmorph.experiments.jsonio import atomic_json
from urbanmorph.experiments.runner import load_run

RUNS = ROOT / "outputs" / "m16" / "runs"
OUT = ROOT / "outputs" / "m16"
PLAN = json.loads((ROOT / "configs" / "m16_plans" / "replay.json").read_text())["runs"]
TERRAIN = [("street_km", "street km", 2), ("empty", "empty", 2), ("share_gt15", "> 15 % share", 3),
           ("share_gt10", "> 10 % share", 3), ("grade_p90_m13", "grade p90 (M13, 30 m)", 3),
           ("contour_align", "gradient alignment (M13)", 3), ("coverage_60", "coverage 60 m", 3),
           ("od_unreach_land", "OD unreachable", 3), ("bridges", "bridges", 2)]
SLOPED = ("incline8", "incline15", "ridge", "valley", "water")
B = 5000


def find(**kw):
    """The plan spec with exactly these keys (others absent)."""
    hits = [s for s in PLAN if all(s.get(k) == v for k, v in kw.items())
            and all(k in kw or k in ("seeds", "style") for k in s)]
    if len(hits) != 1:
        raise KeyError(f"{kw}: {len(hits)} specs")
    return hits[0]


def rows(spec) -> dict:
    r = load_run(spec, RUNS)
    if r is None:
        return {}
    return {(x["site"], int(sd)): x for sd, v in r["seeds"].items() for x in v["rows"]}


def val(x, k):
    v = x.get(k)
    return float(v) if v is not None and np.isfinite(v) else np.nan


def mean_ci(R: dict, k: str, keep=None):
    keys = [key for key in R if keep is None or keep(key[0])]
    v = np.array([val(R[key], k) for key in keys])
    return float(np.nanmean(v)) if np.isfinite(v).any() else np.nan


def paired(A: dict, Bd: dict, k: str, keep=None, rng=None):
    """Mean of B - A over shared (site, seed), two-level bootstrap CI."""
    rng = rng or np.random.default_rng(16)
    keys = [key for key in A if key in Bd and (keep is None or keep(key[0]))]
    d = {}
    for s, sd in keys:
        x = val(Bd[(s, sd)], k) - val(A[(s, sd)], k)
        if np.isfinite(x):
            d.setdefault(s, []).append(x)
    if not d:
        return np.nan, np.nan, np.nan
    sites = list(d)
    est = float(np.mean([np.mean(d[s]) for s in sites]))
    bs = []
    for _ in range(B):
        ss = rng.choice(sites, len(sites))
        bs.append(np.mean([np.mean(rng.choice(d[s], len(d[s]))) for s in ss]))
    return est, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def f(x, n=3):
    return "–" if x is None or not np.isfinite(x) else f"{x:.{n}f}"


def cond(site: str) -> str:
    return site.split("_", 1)[1]


def main():
    L, J = ["# M16 part 1: milestone replays and terrain-regression diagnosis", "",
            "Generated by `scripts/m16_replay_report.py` from `configs/m16_plans/replay.json`. Seeds 101–105. "
            "Exposure: share of ground street length steeper than 15 % / 10 % over consecutive 10 m sub-spans on the "
            "true raster; grade p90 (M13): per-edge maximum over sliding 30 m spans. CIs: two-level bootstrap.", ""], {}
    # R1: historical configurations
    L += ["## R1. Historical configurations (demo landscapes, learned start head, each milestone's own loop)", "",
          "| Method | " + " | ".join(n for _, n, _ in TERRAIN) + " |", "|---|" + "---|" * len(TERRAIN)]
    R1 = {}
    for m in ["M12-loop", "M12-HR", "A", "M*", "M*+repair", "P", "M13-SMC", "NA-myopic", "NA-fixed", "NA-adaptive",
              "NA-random", "NA-SMC"]:
        R1[m] = rows(find(sites="demo_scen", backbone="TN_s0", method=m))
        L.append(f"| {m} | " + " | ".join(f(mean_ci(R1[m], k), n) for k, _, n in TERRAIN) + " |")
    J["R1"] = {m: {k: mean_ci(R1[m], k) for k, _, _ in TERRAIN} for m in R1}
    L += ["", "Paired against M12-HR (the configuration of every M12 demo), same landscape and seed:", "",
          "| Method − M12-HR | > 15 % share [95% CI] | street km [95% CI] |", "|---|---|---|"]
    for m in ["M12-loop", "A", "M*", "NA-fixed", "NA-SMC"]:
        a = paired(R1["M12-HR"], R1[m], "share_gt15")
        b = paired(R1["M12-HR"], R1[m], "street_km")
        L.append(f"| {m} | {f(a[0])} [{f(a[1])}, {f(a[2])}] | {f(b[0], 2)} [{f(b[1], 2)}, {f(b[2], 2)}] |")
    # densest-of-4 vs first (M12 demo selection)
    L += ["", "Demo selection (M12 single-tile demos kept the densest of 4 samples; M13/M14 the first): seeds 101–104",
          "", "| Method | > 15 % share, first | densest of 4 | street km first | densest |", "|---|---|---|---|---|"]
    for m in ["M12-HR", "M12-loop", "M*", "NA-fixed"]:
        sites = sorted({s for s, _ in R1[m]})
        first, dense, kf, kd = [], [], [], []
        for s in sites:
            cand = [R1[m][(s, sd)] for sd in (101, 102, 103, 104) if (s, sd) in R1[m]]
            if not cand:
                continue
            best = max(cand, key=lambda x: val(x, "street_km") if np.isfinite(val(x, "street_km")) else -1)
            first.append(val(cand[0], "share_gt15")), dense.append(val(best, "share_gt15"))
            kf.append(val(cand[0], "street_km")), kd.append(val(best, "street_km"))
        L.append(f"| {m} | {f(np.nanmean(first))} | {f(np.nanmean(dense))} | {f(np.nanmean(kf), 2)} | {f(np.nanmean(kd), 2)} |")
    # R2 matched
    for sites in ("syn_eval", "demo_scen"):
        keep = (lambda s: cond(s) in SLOPED) if sites == "syn_eval" else None
        L += ["", f"## R2. Matched comparisons on `{sites}` (fixed start, same seeds and evaluator)"
                  + (" — sloped and river conditions" if keep else ""), "",
              "| Method | " + " | ".join(n for _, n, _ in TERRAIN) + " |", "|---|" + "---|" * len(TERRAIN)]
        R2 = {}
        for m in ["A", "M*", "M*+repair", "P", "M13-SMC", "NA-myopic", "NA-fixed", "NA-adaptive", "NA-random", "NA-SMC"]:
            R2[m] = rows(find(sites=sites, backbone="TN_s0", method=m, start="centre"))
            L.append(f"| {m} | " + " | ".join(f(mean_ci(R2[m], k, keep), n) for k, _, n in TERRAIN) + " |")
        for m in ("M*", "NA-fixed"):
            R2[m + " cap"] = rows(find(sites=sites, backbone="TN_s0", method=m, start="centre", grade_cap="real_p99"))
            L.append(f"| {m} + M12 grade cap | " + " | ".join(f(mean_ci(R2[m + ' cap'], k, keep), n) for k, _, n in TERRAIN) + " |")
        for bb in ("TNlp_s0", "TNse_s0"):
            for m in ("A", "M*", "NA-fixed"):
                R2[f"{m} {bb}"] = rows(find(sites=sites, backbone=bb, method=m, start="centre"))
                L.append(f"| {m} ({bb}) | " + " | ".join(f(mean_ci(R2[f'{m} {bb}'], k, keep), n) for k, _, n in TERRAIN) + " |")
        for m in ("A", "M*", "NA-fixed"):
            R2[f"{m} flat"] = rows(find(sites=sites, backbone="TN_s0", method=m, start="centre", shown="flatten"))
            L.append(f"| {m}, shown flattened terrain | " + " | ".join(f(mean_ci(R2[f'{m} flat'], k, keep), n) for k, _, n in TERRAIN) + " |")
        J[f"R2_{sites}"] = {m: {k: mean_ci(R2[m], k, keep) for k, _, _ in TERRAIN} for m in R2}
        L += ["", "Paired effects (same site and seed):", "", "| Contrast | > 15 % share [95% CI] | > 10 % share | street km |",
              "|---|---|---|---|"]
        contrasts = [("A", "M*", "M* − A (terrain potentials + hard rules)"),
                     ("M*", "NA-fixed", "NA-fixed − M* (network potentials + look-ahead)"),
                     ("M*", "M* cap", "M* + M12 grade cap − M*"), ("NA-fixed", "NA-fixed cap", "NA-fixed + cap − NA-fixed"),
                     ("A flat", "A", "A: true − flattened input (learned terrain response)"),
                     ("M* flat", "M*", "M*: true − flattened input"), ("NA-fixed flat", "NA-fixed", "NA-fixed: true − flattened"),
                     ("M*", "M* TNlp_s0", "M*: TNlp − TN"), ("M*", "M* TNse_s0", "M*: TNse − TN")]
        for a, b, name in contrasts:
            c = [paired(R2[a], R2[b], k, keep) for k in ("share_gt15", "share_gt10", "street_km")]
            L.append(f"| {name} | {f(c[0][0])} [{f(c[0][1])}, {f(c[0][2])}] | {f(c[1][0])} [{f(c[1][1])}, {f(c[1][2])}] "
                     f"| {f(c[2][0], 2)} [{f(c[2][1], 2)}, {f(c[2][2], 2)}] |")
            J.setdefault(f"contrasts_{sites}", {})[name] = c
        if sites == "syn_eval":
            L += ["", "Mismatch control (sampler shown the terrain rotated 90°; scored on the true terrain):", "",
                  "| Sampler | > 15 % share, true | mismatched | difference [95% CI] |", "|---|---|---|---|"]
            for m in ("A", "M*", "NA-fixed"):
                mm = rows(find(sites="syn_eval_nonflat", backbone="TN_s0", method=m, start="centre", shown="syn_eval_mismatch"))
                c = paired(R2[m], mm, "share_gt15", keep)
                L.append(f"| {m} | {f(mean_ci(R2[m], 'share_gt15', keep))} | {f(mean_ci(mm, 'share_gt15'))} | "
                         f"{f(c[0])} [{f(c[1])}, {f(c[2])}] |")
        L += ["", "Per condition, > 15 % share (true input):", "", "| Method | " + " | ".join(
            sorted({cond(s) for s, _ in R2['M*']})) + " |", "|---|" + "---|" * len({cond(s) for s, _ in R2['M*']})]
        for m in ("A", "M*", "NA-fixed", "M* cap", "A flat", "M* flat"):
            cs = sorted({cond(s) for s, _ in R2[m]})
            L.append(f"| {m} | " + " | ".join(f(np.nanmean([val(x, 'share_gt15') for (s, _), x in R2[m].items()
                                                             if cond(s) == c])) for c in cs) + " |")
    (OUT / "replay_report.md").write_text("\n".join(L) + "\n")
    atomic_json(OUT / "replay_report.json", J)
    print("\n".join(L))


if __name__ == "__main__":
    main()
