"""Milestone 16, part 1: post-hoc re-reading of the stored M15 synthetic runs (no new generation).

Recomputes, per sampler and style, the flat-site means and the paired (same seed) style-on minus style-off differences
for the M15 descriptor AND for network outcomes the style rules do not optimise (road length, loops, junction shares,
dead ends, blocks, OD reachability), plus the per-decision stop rate from the run logs. Seeds are resampled with a
percentile bootstrap (10 seeds on one flat site: within-site uncertainty only).

    python scripts/m16_posthoc_m15.py        ->  outputs/m16/posthoc_m15.{json,md}

POST-HOC: written after the M15 results were seen; it changes no M15 verdict (docs/M15_POSTHOC_CRITIQUE.md).
"""
from __future__ import annotations

import glob
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from urbanmorph.experiments.jsonio import atomic_json  # noqa: E402

RUNS = ROOT / "outputs" / "m15" / "runs"
OUT = ROOT / "outputs" / "m16"
SAMPLERS = ("Mstar", "NA-fixed")
STYLES = ("grid", "organic", "radial", "culdesac")
FEATURES = [("orth_order", "R4"), ("rt", "radial+tangential share"), ("street_km", "street km"),
            ("loops_per_km2", "loops / km2"), ("share_4way", "4-way share"), ("share_3way", "3-way share"),
            ("deadend_per_km", "dead ends / km"), ("blocks", "closed blocks"), ("block_area_med", "median block m2"),
            ("od_unreach", "OD unreachable"), ("stop_rate", "stop rate / decision")]
B = 4000


def rows(sampler: str, style: str, site: str = "eval_flat") -> dict[int, dict]:
    want = {"sites": "syn_eval", "backbone": "TN_s0", "style": style, "start": "centre",
            "method": sampler.replace("Mstar", "M*")}
    f = [d for d in (json.loads(Path(x).read_text()) for x in glob.glob(str(RUNS / f"syn_eval__TN_s0__{sampler}__{style}__*.json")))
         if {k: v for k, v in d["spec"].items() if k != "seeds"} == want]    # the confirmatory run (amendment 2):
    if len(f) != 1:                                                          # fixed start, no other override
        raise SystemExit(f"expected one confirmatory run for {sampler}/{style}, found {len(f)}")
    out = {}
    for sd, v in f[0]["seeds"].items():
        for r in v["rows"]:
            if r["site"] == site:
                r = dict(r)
                r["rt"] = r["radial_share"] + r["tangential_share"]
                lg = r.get("log", {})
                n = lg.get("stop", 0) + lg.get("committed", 0)
                r["stop_rate"] = lg.get("stop", 0) / n if n else np.nan
                out[int(sd)] = r
    return out


def val(r, k):
    x = r.get(k)
    return float(x) if x is not None and np.isfinite(x) else np.nan


def paired(off: dict, on: dict, k: str, rng):
    seeds = sorted(set(off) & set(on))
    d = np.array([val(on[s], k) - val(off[s], k) for s in seeds])
    d = d[np.isfinite(d)]
    if len(d) < 3:
        return {"n": int(len(d)), "diff": float(np.mean(d)) if len(d) else None, "lo": None, "hi": None}
    bs = rng.choice(d, (B, len(d))).mean(1)
    return {"n": int(len(d)), "diff": float(d.mean()), "lo": float(np.percentile(bs, 2.5)),
            "hi": float(np.percentile(bs, 97.5))}


def main():
    rng = np.random.default_rng(16)
    res = {}
    for sm in SAMPLERS:
        off = rows(sm, "off")
        res[sm] = {"off": {k: float(np.nanmean([val(r, k) for r in off.values()])) for k, _ in FEATURES}}
        for st in STYLES:
            on = rows(sm, st)
            res[sm][st] = {k: {"mean_on": float(np.nanmean([val(r, k) for r in on.values()])),
                               "n_on": int(np.isfinite([val(r, k) for r in on.values()]).sum()),
                               **paired(off, on, k, rng)} for k, _ in FEATURES}
    OUT.mkdir(parents=True, exist_ok=True)
    atomic_json(OUT / "posthoc_m15.json", res)

    fmt = lambda x: "–" if x is None or not np.isfinite(x) else (f"{x:.0f}" if abs(x) >= 100 else f"{x:.2f}")
    L = ["# M15 post-hoc re-reading (flat site, 10 seeds, stored runs)", "",
         "POST-HOC (2026-11-21). Paired style on − off on `eval_flat`, seed-bootstrap 95 % CI (within one site). "
         "n = seeds where both values are defined (NaN: no junctions, no blocks or empty network). "
         "Generated by `scripts/m16_posthoc_m15.py`.", ""]
    for sm in SAMPLERS:
        L += [f"## {sm.replace('Mstar', 'M*')}", "",
              "| Outcome | off | " + " | ".join(f"{s} on − off [95% CI] (n)" for s in STYLES) + " |",
              "|---|---|" + "---|" * len(STYLES)]
        for k, name in FEATURES:
            cells = []
            for st in STYLES:
                c = res[sm][st][k]
                cells.append(f"{fmt(c['diff'])} [{fmt(c['lo'])}, {fmt(c['hi'])}] ({c['n']})" if c["diff"] is not None
                             else "–")
            L.append(f"| {name} | {fmt(res[sm]['off'][k])} | " + " | ".join(cells) + " |")
        L.append("")
    (OUT / "posthoc_m15.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
