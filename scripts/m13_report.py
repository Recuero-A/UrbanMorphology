def fig_examples(M):
    """Real vs A vs M* on four DEV-B tiles (two steepest, two median): fig 8; and the 3 worst-S_T-contribution tiles: fig 12."""
    from urbanmorph.graphs.road_graph import RoadGraph
    ra, rm = load(rid_of("devB", "TN_s0", "TN", "A", M)), load(rid_of("devB", "TN_s0", "TN", "M", M))
    if ra is None or rm is None:
        return
    tiles = ex.tile_set("devB")
    real = an.real_rows("devB")
    order = np.argsort([r["slope_mean_ctx"] for r in real])
    pick = [order[-1], order[-2], order[len(order) // 2], order[len(order) // 3]]

    def draw(a, G, d, title):
        z = d["elev"][64:192, 64:192]
        gy, gx = np.gradient(z, 4.0)
        a.imshow(np.clip(0.6 + 0.5 * (gx - gy) / np.sqrt(1 + gx ** 2 + gy ** 2), 0, 1), cmap="gray", extent=(0, 512, 0, 512), vmin=0, vmax=1.2)
        w = d["water"][64:192, 64:192]
        a.imshow(np.ma.masked_where(w == 0, w), cmap="Blues", vmin=0, vmax=2, extent=(0, 512, 0, 512), alpha=0.9)
        for (x0, y0, x1, y1), st in zip(G.segments(), G.structs()):
            a.plot([x0, x1], [y0, y1], color="#c0392b" if st == 1 else INK, lw=2.2 if st == 1 else 0.9)
        a.set_xticks([]), a.set_yticks([])
        a.set_xlim(0, 512), a.set_ylim(0, 512)
        a.set_title(title, fontsize=9)

    def graph_of(res, k):
        G = res["seeds"]["1"]["graphs"][k]
        return RoadGraph(np.array(G["nodes"]).reshape(-1, 2), np.array(G["edges"], int).reshape(-1, 2), np.zeros(len(G["nodes"]), bool),
                         np.array(G["cls"]), None, np.array(G["st"]))
    fig, ax = plt.subplots(len(pick), 3, figsize=(9.6, 3.3 * len(pick)))
    for r, k in enumerate(pick):
        draw(ax[r, 0], tiles[k]["graph"], tiles[k]["d"], f"real {tiles[k]['sid']}")
        draw(ax[r, 1], graph_of(ra, k), tiles[k]["d"], "A standard")
        draw(ax[r, 2], graph_of(rm, k), tiles[k]["d"], "M* selected")
    fig.suptitle("DEV-B tiles, TN_s0, inference seed 1 (bridges red). Conditional generation on the real terrain.", fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / "fig08_real_vs_generated.png", dpi=130)
    plt.close(fig)
    # failure cases: largest density deficit under M*
    gm = an.tile_means(rm)
    deficit = np.array([max(0, 1 - g["m12_street_km_per_km2"] / max(x["m12_street_km_per_km2"], 1e-9)) for g, x in zip(gm, real)])
    worst = np.argsort(-deficit)[:3]
    fig, ax = plt.subplots(len(worst), 2, figsize=(6.6, 3.3 * len(worst)))
    for r, k in enumerate(worst):
        draw(ax[r, 0], tiles[k]["graph"], tiles[k]["d"], f"real {tiles[k]['sid']}")
        draw(ax[r, 1], graph_of(rm, k), tiles[k]["d"], f"M*: density deficit {deficit[k]:.0%}")
    fig.suptitle("Failure cases: the three DEV-B tiles with the largest M* street-length deficit (TN_s0)", fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / "fig12_failure_cases.png", dpi=130)
    plt.close(fig)


