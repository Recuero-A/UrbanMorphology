def fig_trace():
    """Figs 2-6 from a traced run of M* on one steep DEV-B tile: turtle state, candidates, scores, look-ahead, choices."""
    f = OUT / "trace.json"
    if not f.exists():
        return
    tr = json.loads(f.read_text())
    d = {k: np.array(v) for k, v in tr["tile"].items()}
    z = d["elev"][64:192, 64:192]
    gy, gx = np.gradient(z, 4.0)
    shade = np.clip(0.6 + 0.5 * (gx - gy) / np.sqrt(1 + gx ** 2 + gy ** 2), 0, 1)
    # fig 2: the turtle state (crop channels of one decision)
    cr = np.array(tr["crop"], float)
    names = ["streets drawn", "open nodes", "outside tile", "relative elevation", "slope", "water"][:cr.shape[0]]
    fig, ax = plt.subplots(1, len(names), figsize=(2.3 * len(names), 2.6))
    for a, ch, n in zip(np.atleast_1d(ax), cr, names):
        a.imshow(ch, cmap="viridis")
        a.set_title(n, fontsize=8)
        a.set_xticks([]), a.set_yticks([])
    fig.suptitle("Terrain-conditioned turtle state at one node (48 x 48 crop, 4 m; rotated so the heading points up)", fontsize=9)
    fig.tight_layout()
    fig.savefig(FIG / "fig02_turtle_state.png", dpi=150)
    plt.close(fig)
    decs = [x for x in tr["decisions"] if len(x["cands"]) > 1][:200]
    if not decs:
        return
    # pick a decision with at least one rejected and one accepted candidate
    pick = next((x for x in decs if any(c["reason"] for c in x["cands"]) and any(not c["reason"] for c in x["cands"])), decs[0])
    u = np.array(pick["u"])
    fig, ax = plt.subplots(1, 3, figsize=(14, 4.8))
    for a in ax:
        a.imshow(shade, cmap="gray", extent=(0, 512, 0, 512), vmin=0, vmax=1.2)
        a.set_xlim(u[0] - 120, u[0] + 120), a.set_ylim(u[1] - 120, u[1] + 120)
        a.set_xticks([]), a.set_yticks([])
    lw = np.array([c["lw"] if c["lw"] is not None else -np.inf for c in pick["cands"]])
    for k, c in enumerate(pick["cands"]):
        q = np.array(c["q"])
        col = "#c0392b" if c["reason"] else PAL[0]
        ax[0].plot([u[0], q[0]], [u[1], q[1]], color=col, lw=1.6)
        ax[1].plot([u[0], q[0]], [u[1], q[1]], color=plt.cm.viridis(1 / (1 + np.exp(-lw[k]))) if np.isfinite(lw[k]) else "#c0392b", lw=2)
        ax[1].annotate(f"{lw[k]:+.1f}" if np.isfinite(lw[k]) else c["reason"].replace("_", " "), q, fontsize=7, color=INK)
        if c.get("rollout"):
            p = np.array(c["rollout"])
            ax[2].plot(p[:, 0], p[:, 1], "-o", ms=2, lw=1.2, color=PAL[k % len(PAL)], alpha=0.9)
    ax[0].plot(*u, "o", color=INK)
    ax[0].set_title("K candidate steps (red = hard-infeasible)", fontsize=9, loc="left")
    ax[1].set_title("log-potential of each committed edge", fontsize=9, loc="left")
    ax[2].set_title("look-ahead roll-outs of each candidate", fontsize=9, loc="left")
    fig.tight_layout()
    fig.savefig(FIG / "fig03_05_candidates_scores_lookahead.png", dpi=150)
    plt.close(fig)
    # fig 6: accepted vs rejected over the whole run
    fig, ax = plt.subplots(figsize=(6, 6))
    ax.imshow(shade, cmap="gray", extent=(0, 512, 0, 512), vmin=0, vmax=1.2)
    for x in tr["decisions"]:
        u = np.array(x["u"])
        for k, c in enumerate(x["cands"]):
            q = np.array(c["q"])
            if c["reason"]:
                ax.plot([u[0], q[0]], [u[1], q[1]], color="#c0392b", lw=0.5, alpha=0.5)
            elif k == x["chosen"]:
                ax.plot([u[0], q[0]], [u[1], q[1]], color=INK, lw=1.4)
    ax.set_xticks([]), ax.set_yticks([])
    ax.set_xlim(0, 512), ax.set_ylim(0, 512)
    ax.set_title("Accepted steps (black) and hard-rejected candidates (red)", fontsize=9, loc="left")
    fig.tight_layout()
    fig.savefig(FIG / "fig06_accepted_vs_rejected.png", dpi=150)
    plt.close(fig)


