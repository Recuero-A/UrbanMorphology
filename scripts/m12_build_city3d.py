"""Milestone 12: an explorable terrain-aware city: terrain -> streets (a trained model + policy) -> BF parcels and
buildings -> M11 3D scene -> terrain draping, bridges, water -> Blender (GLB, renders) -> Godot check.

    python scripts/m12_build_city3d.py --scenario wide_river --scenario-seed 3 --model TN_s0 --mode HR
    python scripts/m12_build_city3d.py --terrain-tile USA_SAN_e936_n7072 --model TN_s0 --mode HR   # real val_t terrain
    then: Blender (blender/m11_scene.py --tile DIR) and python scripts/m11_godot.py --root outputs/m12/cities --tiles NAME

Real terrain is used only for development tiles (val, val_t). Buildings are generated by BF (M10) unchanged and
then FILTERED minimally (spec §19): a building whose footprint touches water, or whose ground slope (landform, 32 m)
exceeds BUILD_SLOPE, is removed; the counts are recorded. Every geometric adjustment of terrain3d is reported in
validation.json. Synthetic landscapes get no geographic coordinates.
"""
import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np
import shapely
import torch

from urbanmorph.city3d.cameras import cameras
from urbanmorph.city3d.convert import from_generated
from urbanmorph.city3d.format import save_city, validate_city
from urbanmorph.city3d.scene import build_scene, save_scene
from urbanmorph.city3d.terrain3d import Surfaces, apply_terrain
from urbanmorph.config import PROJECT_ROOT
from urbanmorph.data.m12_index import load_index_m12
from urbanmorph.graphs.generate import sample_graphs
from urbanmorph.graphs.terrain_generate import TerrainPolicy, terrain_of
from urbanmorph.graphs.terrain_metrics import landform_gradient
from urbanmorph.terrain.road_feasibility import Thresholds, water_kind_at
from urbanmorph.terrain.synthesis import generate, scenario

OUT = PROJECT_ROOT / "outputs" / "m12" / "cities"
TERRAIN = PROJECT_ROOT / "data" / "processed" / "m12" / "terrain"
AUDIT11 = PROJECT_ROOT / "outputs" / "m11" / "audit"
BUILD_SLOPE = 0.35       # engineering assumption: landform slope above which BF buildings are not placed (spec §19)


def terrain_dict(a):
    if a.terrain_tile:
        idx = load_index_m12().set_index("sample_id")
        if idx.loc[a.terrain_tile].split not in ("val", "val_t"):
            raise SystemExit("real terrain cities use development tiles (val, val_t) only")
        return dict(np.load(TERRAIN / f"{a.terrain_tile}.npz")), f"real:{a.terrain_tile}"
    t = generate(scenario(a.scenario, a.scenario_seed), -256, -256, 768, 768)
    return {"elev": t.elev, "valid": np.ones(t.elev.shape, bool), "water": t.water_kind,
            "water_surface": t.water_surface}, f"procedural:{a.scenario}:seed{a.scenario_seed}"


def buildable(buildings, t):
    """Minimal buildability filter: no building on water or on land steeper than BUILD_SLOPE (landform slope, 32 m).
    Returns (kept buildings, removed for water, removed for slope)."""
    gx, gy = landform_gradient(t)
    slope = np.hypot(gx, gy)
    keep, rm_w, rm_s = [], 0, 0
    for b in buildings:
        fp = shapely.Polygon(np.asarray(b["footprint"][0])[:, :2])
        pts = np.vstack([np.asarray(fp.exterior.coords), np.asarray(fp.representative_point().coords)])
        r, c = t.rc(pts[:, 0], pts[:, 1])
        s = slope[np.clip(np.round(r).astype(int), 0, slope.shape[0] - 1), np.clip(np.round(c).astype(int), 0, slope.shape[1] - 1)]
        if (water_kind_at(t, pts[:, 0], pts[:, 1]) > 0).any():
            rm_w += 1
        elif np.nanmax(s) > BUILD_SLOPE:
            rm_s += 1
        else:
            keep.append(b)
    return keep, rm_w, rm_s


def m13_fixes(city, d, g, max_access_m: float = 50.0) -> dict:
    """Milestone 13 downstream demonstration fixes (kept separate from road generation; counts reported):
    parcels and land-use polygons are clipped out of water (so no trees stand in lakes), and buildings whose footprint
    is farther than ``max_access_m`` from every street segment are removed (inaccessible clusters)."""
    import shapely.affinity
    import shapely.geometry
    from rasterio import features
    w = (d["water"][64:192, 64:192] > 0).astype(np.uint8)
    polys = [shapely.geometry.shape(gm) for gm, v in features.shapes(w, mask=w > 0) if v == 1]
    water = shapely.affinity.affine_transform(shapely.union_all(polys), [4.0, 0, 0, -4.0, 0, 512.0]) if polys else shapely.Polygon()
    rep = {"parcels_clipped": 0, "parcels_dropped": 0, "landuse_clipped": 0, "landuse_dropped": 0, "buildings_inaccessible": 0}

    def clip(items, key):
        out = []
        for it in items:
            P_ = shapely.Polygon(np.asarray(it["polygon"][0])[:, :2])
            if water.is_empty or not P_.intersects(water):
                out.append(it)
                continue
            q = shapely.make_valid(P_.difference(water.buffer(1.0)))
            q = max(getattr(q, "geoms", [q]), key=lambda x: x.area) if not q.is_empty else q
            if q.is_empty or q.geom_type != "Polygon" or q.area < 20:
                rep[f"{key}_dropped"] += 1
                continue
            rep[f"{key}_clipped"] += 1
            out.append({**it, "polygon": [np.asarray(q.exterior.coords).tolist()]})
        return out
    city["parcels"] = clip(city.get("parcels", []), "parcels")
    city["landuse"] = clip(city.get("landuse", []), "landuse")
    seg = g.segments() if len(g.edges) else np.zeros((0, 4))
    lines = shapely.multilinestrings([[s_[:2], s_[2:]] for s_ in seg]) if len(seg) else None
    keep = []
    for b in city["buildings"]:
        c = shapely.Polygon(np.asarray(b["footprint"][0])[:, :2])
        if lines is None or c.distance(lines) > max_access_m:
            rep["buildings_inaccessible"] += 1
            continue
        keep.append(b)
    city["buildings"] = keep
    return rep


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--terrain-tile")
    ap.add_argument("--scenario")
    ap.add_argument("--scenario-seed", type=int, default=0)
    ap.add_argument("--model", default="TN_s0")
    ap.add_argument("--mode", default="HR", choices=["none", "R", "HR", "HRV", "P"])
    ap.add_argument("--seed", type=int, default=2041, help="street sampling seed")
    ap.add_argument("--country", default="united_states", choices=["spain", "united_states"])
    ap.add_argument("--sampler", help="Milestone 13: a tc_sampler preset (e.g. energy_la); overrides --mode")
    ap.add_argument("--overrides", default="{}", help="Milestone 13: JSON overrides of the preset")
    ap.add_argument("--potentials", default="TN", help="Milestone 13: configs/m13_potentials/<name>.json")
    ap.add_argument("--m13-fixes", action="store_true", help="Milestone 13 downstream fixes: parcels / green clipped "
                    "out of water (no trees in lakes), buildings > 50 m from any street removed (inaccessible)")
    a = ap.parse_args()
    from m10_integrate import bf_layouts  # noqa: E402
    from m12_evaluate import load_model  # noqa: E402
    from m6_build_objects import load_objects  # noqa: E402
    t0 = time.time()
    d, src = terrain_dict(a)
    t = terrain_of(d)
    if "water_surface" in d:
        t.water_surface = d["water_surface"]
    th = Thresholds.load(PROJECT_ROOT / "configs" / "m12_feasibility.json")
    if a.sampler:
        from m13_experiments import load_backbone  # noqa: E402
        from urbanmorph.graphs.tc_potentials import Potentials
        from urbanmorph.graphs.tc_sampler import preset, sample_tc
        device = "mps" if torch.backends.mps.is_available() else "cpu"
        model, names, norm, _ = load_backbone(a.model, device)
        pots = Potentials.load(PROJECT_ROOT / "configs" / "m13_potentials" / f"{a.potentials}.json")
        cfg = preset(a.sampler, **json.loads(a.overrides))
        gs, st, _ = sample_tc(model, [d], names, norm, pots, cfg, seed=a.seed, device=device)
        g, pstats, model_name = gs[0], dict(st[0]), a.model           # the FIRST sample (no cherry-picking)
        a.mode = f"tc-{a.sampler}"
    elif a.mode == "P":
        from urbanmorph.graphs.procedural_terrain import sample_P
        g, pstats = sample_P(t, np.random.default_rng(a.seed), 120.0, th), {}
        model_name = "P"
    else:
        device = "mps" if torch.backends.mps.is_available() else "cpu"
        model, names, norm = load_model(a.model, device)
        pol = TerrainPolicy([d] * 4, names, norm, mode=a.mode, th=th)
        gs = sample_graphs(model, 4, device=device, seed=a.seed, temperature=0.5, terrain=pol)
        k = int(np.argmax([len(x.edges) for x in gs]))                  # the densest of 4 samples
        g, pstats, model_name = gs[k], dict(pol.stats[k]), a.model
    t_streets = time.time() - t0
    cw = load_objects()["class_widths"]
    (st, P), = bf_layouts([g], [a.country], cw, seed=0)
    priors = json.loads((AUDIT11 / "height_priors.json").read_text())
    tag = (a.terrain_tile or f"{a.scenario}{a.scenario_seed}") + f"_{model_name}_{a.mode}_s{a.seed}"
    city = from_generated(f"m12_{tag}", st.graph, st, P, cw, a.country, priors,
                          {"value": 3.0, "source": "default 3.0 m"}, a.seed,
                          {"streets": f"{model_name} mode {a.mode}, T=0.5, sampling seed {a.seed}", "terrain": src,
                           "parcels_buildings": "BF (M10), filtered for water and slope (M12)",
                           "heights": "synthetic (city3d.heights)", "roofs_styles": "synthetic (city3d.style)"})
    keep, rm_w, rm_s = buildable(city["buildings"], t)
    city["buildings"] = keep
    fixes = m13_fixes(city, d, g) if a.m13_fixes else None
    city["metadata"]["synthetic_terrain"] = src.startswith("procedural")
    d_out = OUT / city["metadata"]["tile_id"]
    d_out.mkdir(parents=True, exist_ok=True)
    err = validate_city(city)
    save_city(city, d_out / "city.json")
    groups, mats, rep = build_scene(city)
    groups, mats, trep = apply_terrain(groups, mats, city, t, g)
    save_scene(d_out / "meshes.npz", groups, mats)
    cams = cameras(city)
    S = Surfaces(t)
    for k in ("street", "closeup"):
        if k in cams:
            for key in ("location", "look_at"):
                p = cams[k][key]
                p[2] += float(S.road(np.array([p[0]]), np.array([p[1]]))[0])
    for key in ("spawn", "look_at"):
        p = cams["godot_spawn"][key]
        p[1] += float(S.road(np.array([p[0]]), np.array([-p[2]]))[0])
    zmin, zmax = float(np.nanmin(t.elev)), float(np.nanmax(t.elev))
    for k in ("aerial", "oblique"):
        if k in cams:
            cams[k]["location"][2] += zmax
            if "look_at" in cams[k]:
                cams[k]["look_at"][2] += (zmin + zmax) / 2
    cams["surround_z"] = trep["surround_z"]
    (d_out / "cameras.json").write_text(json.dumps(cams, indent=1))
    (d_out / "viewer.json").write_text(json.dumps(cams["godot_spawn"]))
    rep["terrain3d"] = trep
    rep["buildability_filter"] = {"removed_water": rm_w, "removed_slope": rm_s, "kept": len(keep), "build_slope_max": BUILD_SLOPE}
    if fixes is not None:
        rep["m13_downstream_fixes"] = fixes
    rep["streets"] = {"edges": int(len(g.edges)), "bridges": int((g.structs() == 1).sum()), "policy": pstats,
                      "seconds": round(t_streets, 1)}
    rep["format_errors"] = err
    (d_out / "validation.json").write_text(json.dumps({k: v for k, v in rep.items() if k != "buildings"}, indent=1, default=str))
    np.save(d_out / "streets.npy", np.c_[g.segments(), g.classes(), g.structs()])
    print(json.dumps({"dir": str(d_out), **rep["streets"], **rep["buildability_filter"], **trep}, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
